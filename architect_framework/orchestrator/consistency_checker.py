from typing import List, Dict, Any, Optional
from architect_framework.registry.rule_registry import RuleRegistry
from architect_framework.models.correspondence import (
    CorrespondenceRule,
    ArchitectureView,
    ConsistencyCheckResult,
)


class ConsistencyChecker:
    """
    ISO 42010 Cross-Viewpoint Consistency Checker.
    Enforces Correspondence Rules across views generated by agents.
    """

    def __init__(self, rule_registry: Optional[RuleRegistry] = None):
        self.rule_registry = rule_registry or RuleRegistry()

    def validate_views(
        self, views: Dict[str, ArchitectureView]
    ) -> List[ConsistencyCheckResult]:
        """
        Evaluates registered rules against active architecture views.
        """
        results = []
        for rule in self.rule_registry.list_all_rules():
            source_vp = rule.source_viewpoint
            target_vp = rule.target_viewpoint

            source_view = views.get(source_vp)
            target_view = views.get(target_vp)

            violations = []
            passed = True

            if rule.rule_type in {"MustExist", "AttributeMatch", "1:1", "1:N"}:
                if source_view and not target_view:
                    passed = False
                    violations.append(
                        f"Target viewpoint '{target_vp}' missing for source viewpoint '{source_vp}'."
                    )
                elif source_view and target_view:
                    for elem in source_view.elements:
                        elem_label = elem.get("id", elem.get("name"))
                        matched_targets = [
                            t_elem
                            for t_elem in target_view.elements
                            if t_elem.get("source_id") == elem.get("id")
                            or t_elem.get("name") == elem.get("name")
                        ]
                        if not matched_targets:
                            passed = False
                            violations.append(
                                f"Element '{elem_label}' in '{source_vp}' is not mapped to any element in '{target_vp}'."
                            )
                        elif rule.rule_type == "1:1" and len(matched_targets) > 1:
                            passed = False
                            violations.append(
                                f"Element '{elem_label}' in '{source_vp}' maps to {len(matched_targets)} elements in '{target_vp}', violating 1:1 rule '{rule.id}'."
                            )
                        elif rule.rule_type == "AttributeMatch":
                            src_attrs = elem.get("attributes")
                            if isinstance(src_attrs, dict) and src_attrs:
                                for key, expected_val in src_attrs.items():
                                    target_vals = [
                                        t_elem["attributes"][key]
                                        for t_elem in matched_targets
                                        if isinstance(t_elem.get("attributes"), dict)
                                        and key in t_elem["attributes"]
                                    ]
                                    if target_vals and all(val != expected_val for val in target_vals):
                                        passed = False
                                        violations.append(
                                            f"Attribute '{key}' on element '{elem_label}' in '{source_vp}' ({expected_val!r}) does not match '{target_vp}' ({target_vals[0]!r})."
                                        )

            results.append(
                ConsistencyCheckResult(
                    rule_id=rule.id,
                    passed=passed,
                    source_viewpoint=source_vp,
                    target_viewpoint=target_vp,
                    violations=violations,
                )
            )

        return results
