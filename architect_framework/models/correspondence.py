from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class CorrespondenceRule(BaseModel):
    """
    ISO 42010 Correspondence Rule enforcing cross-viewpoint consistency.
    """
    id: str = Field(..., description="Rule ID (e.g. CR-001-DDD-CONTAINER-MAPPING)")
    source_viewpoint: str = Field(..., description="Source viewpoint (e.g. Domain Viewpoint)")
    target_viewpoint: str = Field(..., description="Target viewpoint (e.g. Application Viewpoint)")
    rule_type: str = Field(..., description="Type: 1:1, 1:N, MustExist, AttributeMatch")
    expression: str = Field(..., description="Logic or expression rule string")
    error_message: str = Field(..., description="Message if consistency check fails")


class ArchitectureView(BaseModel):
    """
    Represents an Architecture View generated by a Domain Agent.
    """
    viewpoint_id: str
    elements: List[Dict[str, Any]] = Field(default_factory=list)


class ConsistencyCheckResult(BaseModel):
    """
    Result of ISO 42010 Correspondence Rule evaluation.
    """
    rule_id: str
    passed: bool
    source_viewpoint: str
    target_viewpoint: str
    violations: List[str] = Field(default_factory=list)
