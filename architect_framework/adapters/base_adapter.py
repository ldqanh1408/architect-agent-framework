from abc import ABC, abstractmethod
from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field
from architect_framework.models.execution_matrix import OrchestrationContext


class AdapterConfig(BaseModel):
    def model_dump(self, *args, **kwargs):
        if hasattr(super(), "model_dump"):
            return super().model_dump(*args, **kwargs)
        return self.dict(*args, **kwargs)

    """Configuration for a specific LLM model adapter."""
    adapter_name: str = Field(..., description="Name of the adapter (e.g. claude, hermes, codex)")
    model_name: str = Field(..., description="Target LLM model identifier (e.g. claude-3-5-sonnet-20241022, hermes-3-llama-3.1-405b, gpt-4o)")
    provider: str = Field(..., description="LLM provider (e.g. anthropic, nousresearch, openai, ollama, deepseek)")
    temperature: float = Field(0.2, description="Sampling temperature")
    max_tokens: int = Field(4096, description="Maximum completion tokens")
    top_p: Optional[float] = Field(1.0, description="Top-p sampling parameter")
    stop_sequences: Optional[List[str]] = Field(default_factory=list, description="Stop sequence triggers")
    enable_structured_outputs: bool = Field(False, description="Whether to enforce JSON schema structured outputs")
    system_prompt_format: str = Field("standard", description="Formatting mode: standard, xml, chatml, markdown")
    extra_params: Dict[str, Any] = Field(default_factory=dict, description="Additional provider-specific parameters")


class AdapterOutput(BaseModel):
    def model_dump(self, *args, **kwargs):
        if hasattr(super(), "model_dump"):
            return super().model_dump(*args, **kwargs)
        return self.dict(*args, **kwargs)

    """Output payload generated by an adapter ready for API consumption."""
    adapter_name: str
    model_name: str
    provider: str
    system_prompt: str
    user_prompt: Optional[str] = None
    formatted_payload: Dict[str, Any]
    config: AdapterConfig


class BaseModelAdapter(ABC):
    """Abstract Base Class for all LLM Model Adapters in Architect Agent Framework."""

    def __init__(self, config: AdapterConfig):
        self.config = config

    @abstractmethod
    def format_context(
        self,
        context: OrchestrationContext,
        user_request: Optional[str] = None,
        **kwargs
    ) -> AdapterOutput:
        """
        Transforms an OrchestrationContext (E_{i,j}) into a model-specific payload format.
        """
        pass

    def get_config(self) -> AdapterConfig:
        """Returns the current adapter configuration."""
        return self.config


    def sanitize_artifact_output(self, text: str) -> str:
        from architect_framework.sdd_bridge.authoring_qa import repair_frontmatter, strip_thinking_blocks
        return repair_frontmatter(strip_thinking_blocks(text or ""))
